/**
 * 阿里 iconfont → 微信小程序字体图标接入脚本
 *
 * 用法:
 *   1. 在 iconfont 官网挑选图标 → 加入购物车 → 「下载素材 → 仅下载字体」或
 *      「复制代码 → Font class」下载源码包
 *   2. 把源码包里的 iconfont.css 与 iconfont.ttf 解压到 iconfont-src/
 *   3. 按需修改 iconfont-src/map.mjs(页面里的 key → iconfont 类名)
 *   4. 执行:node scripts/gen-iconfont.mjs
 *   5. 输出:src/styles/iconfont.scss(自动被首页引用)
 */
import { existsSync, readFileSync, writeFileSync } from 'node:fs'
import { dirname, join } from 'node:path'
import process from 'node:process'
import { fileURLToPath } from 'node:url'
import { map as ICON_MAP } from '../iconfont-src/map.mjs'

const __dirname = dirname(fileURLToPath(import.meta.url))
const ROOT = join(__dirname, '..')
const CSS_PATH = join(ROOT, 'iconfont-src', 'iconfont.css')
const TTF_PATH = join(ROOT, 'iconfont-src', 'iconfont.ttf')
const OUT_PATH = join(ROOT, 'src', 'styles', 'iconfont.scss')

if (!existsSync(CSS_PATH) || !existsSync(TTF_PATH)) {
  console.error('缺少 iconfont-src/iconfont.css 或 iconfont-src/iconfont.ttf')
  console.error('请先在 https://www.iconfont.cn 挑选图标,下载「Font class」源码包并解压到 iconfont-src/')
  process.exit(1)
}

const css = readFileSync(CSS_PATH, 'utf8')
const ttfBase64 = readFileSync(TTF_PATH).toString('base64')

/* 解析 iconfont.css 中的类名 → unicode */
const rules = new Map()
const re = /\.([\w-]+)(?::?:before)?\s*\{[^}]*content:\s*["']\\?\(?([eE][0-9a-fA-F]{2,5})\)?["']/g
let m = re.exec(css)
while (m !== null) {
  rules.set(m[1], m[2].toLowerCase())
  m = re.exec(css)
}

if (rules.size === 0) {
  console.error('未从 iconfont.css 解析到任何 unicode 映射,请确认下载的是 Font class 模式源码包')
  process.exit(1)
}

const missing = []
let out = `/*
 * AUTO-GENERATED by scripts/gen-iconfont.mjs — DO NOT EDIT
 * 来源:阿里 iconfont · 重新生成前请修改 iconfont-src/map.mjs
 */
@font-face {
  font-family: 'bs-icon';
  src: url('data:font/ttf;base64,${ttfBase64}') format('truetype');
  font-weight: normal;
  font-style: normal;
}

.bs-icon-font {
  font-family: 'bs-icon', sans-serif;
  font-size: 44rpx;
  line-height: 1;
  font-style: normal;
  -webkit-font-smoothing: antialiased;
  -moz-osx-font-smoothing: grayscale;
}\n`

for (const [key, iconClass] of Object.entries(ICON_MAP)) {
  const classBody = iconClass.replace(/^icon-/i, '')
  const unicode = rules.get(iconClass) || rules.get(classBody)
  if (!unicode) {
    missing.push(`${key}  →  ${iconClass}`)
    continue
  }
  out += `\n.bs-icon--${key}::before {\n  content: '\\${unicode}';\n}\n`
}

writeFileSync(OUT_PATH, out, 'utf8')

console.log(`已生成 ${OUT_PATH}(${rules.size} 个图标映射,${Object.keys(ICON_MAP).length} 个页面图标)`)
if (missing.length) {
  console.warn('以下 key 未找到 unicode,请检查 iconfont-src/map.mjs:')
  missing.forEach(warn => console.warn(`  - ${warn}`))
}
else {
  console.log('全部图标映射成功 ✓')
}
